// ToolsStep installs the plan's tools via mise and activates them globally
// with one conf.d snippet per module (issue 0137, replacing 0037's single
// fragment): mise loads ~/.config/mise/conf.d/*.toml as global config, so
// each module's installed tools resolve on PATH. config.toml itself is
// never touched — it may be a managed dotfile. Snippets of modules that no
// longer declare tools are removed (removed tools must stop resolving), as
// is 0037's combined dotdrift.toml; only files carrying the generated-by
// marker are ever removed.
type ToolsStep struct {
	Runner     Runner
	Plan       *resolve.Plan
	ConfigPath string
	// FragmentDir is the conf.d directory holding the per-module snippets
	// (see ToolsFragmentDir). Empty skips the snippets (tests, onboard).
	FragmentDir string
}

var _ apply.Step = (*ToolsStep)(nil)

func (s *ToolsStep) Name() string { return "tools" }

// generatedMarker heads every dotdrift-written conf.d snippet; it is the
// ownership proof the stale-snippet sweep requires before removing a file.
const generatedMarker = "# Generated by dotdrift — do not edit.\n"

func (s *ToolsStep) Run(ctx context.Context) error {
	if s.Runner == nil {
		return fmt.Errorf("no mise runner configured")
	}
	if s.Plan == nil {
		return fmt.Errorf("plan is nil")
	}
	if len(s.Plan.Tools.Versions) == 0 {
		if s.FragmentDir != "" {
			if err := removeStaleSnippets(s.FragmentDir, nil); err != nil {
				return fmt.Errorf("remove stale tools snippets: %w", err)
			}
		}
		return nil
	}
	cfg := GenerateTools(s.Plan.Tools.Versions)
	if err := writeConfig(s.ConfigPath, cfg); err != nil {
		return fmt.Errorf("write tools mise config: %w", err)
	}
	if err := s.Runner.EnsureAndInstall(ctx, s.ConfigPath); err != nil {
		return fmt.Errorf("mise install: %w", err)
	}
	if s.FragmentDir != "" {
		if err := s.writeSnippets(); err != nil {
			return fmt.Errorf("write tools activation snippets: %w", err)
		}
	}
	return nil
}

// moduleTools returns the plan's tools per module: ModuleTools as resolved,
// derived from ToolModules for hand-built plans that only carry that map.
func (s *ToolsStep) moduleTools() map[string]map[string]string {
	if len(s.Plan.Tools.ModuleTools) > 0 {
		return s.Plan.Tools.ModuleTools
	}
	out := make(map[string]map[string]string)
	for tool, modules := range s.Plan.Tools.ToolModules {
		for _, mod := range modules {
			if out[mod] == nil {
				out[mod] = make(map[string]string)
			}
			out[mod][tool] = s.Plan.Tools.Versions[tool]
		}
	}
	return out
}

// writeSnippets writes one marked <module>.toml per module with tools,
// then sweeps marked snippets whose module no longer declares tools.
func (s *ToolsStep) writeSnippets() error {
	perModule := s.moduleTools()
	keep := make(map[string]bool, len(perModule))
	for mod, tools := range perModule {
		if len(tools) == 0 {
			continue
		}
		name := filepath.Base(mod) + ".toml"
		keep[name] = true
		if err := writeConfig(filepath.Join(s.FragmentDir, name), generatedMarker+GenerateTools(tools)); err != nil {
			return err
		}
	}
	return removeStaleSnippets(s.FragmentDir, keep)
}

// removeStaleSnippets deletes conf.d/*.toml files that carry the
// generated-by marker and are not in keep (nil keeps nothing). Foreign
// files — no marker — are never touched. A missing directory is fine.
func removeStaleSnippets(dir string, keep map[string]bool) error {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".toml") || keep[name] {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(b), generatedMarker) {
			continue
		}
		if err := os.Remove(filepath.Join(dir, name)); err != nil {
			return err
		}
	}
	return nil
}

// DotfilesStep runs mise dotfiles apply for the dotfiles in the resolved plan.
type DotfilesStep struct {
	Runner     Runner
	Plan       *resolve.Plan
	ConfigPath string
	Yes        bool
	// Force maps to dotdrift apply --force (issue 0046): replace pre-existing
	// regular files at managed targets (e.g. an app-written file where a
	// symlink should go) instead of aborting with mise's "refusing to
	// overwrite existing files". Default off — refusal is the safety;
	// onboard is the deliberate takeover path.
	Force bool
}

var _ apply.Step = (*DotfilesStep)(nil)

func (s *DotfilesStep) Name() string { return "dotfiles" }

func (s *DotfilesStep) Run(ctx context.Context) error {
	if s.Runner == nil {
		return fmt.Errorf("no mise runner configured")
	}
	if s.Plan == nil {
		return fmt.Errorf("plan is nil")
	}
	if len(s.Plan.Dotfiles.Entries) == 0 {
		return nil
	}
	cfg := GenerateDotfiles(s.Plan.Dotfiles.Entries)
	if err := writeConfig(s.ConfigPath, cfg); err != nil {
		return fmt.Errorf("write dotfiles mise config: %w", err)
	}
	// Force comes from dotdrift apply --force (issue 0046). Default off:
	// apply must refuse to clobber pre-existing files it does not own (mise
	// errors naming them; onboard is the takeover path).
	if err := s.Runner.DotfilesApply(ctx, s.ConfigPath, s.Yes, s.Force); err != nil {
		return fmt.Errorf("mise dotfiles apply: %w", err)
	}
	return nil
}

// HooksStep runs each pre/post hook command as its own mise task from the
// generated apply config. Per-command execution preserves hook order while
// allowing individual hooks to opt out of fail-fast: a command marked
// Optional that exits non-zero is logged at warn and the next command runs.
// cmd/apply.go only constructs HooksSteps for non-empty command lists; Run
// also no-ops on an empty list as a second line of defense.
//
// Each command maps to a mise task named <Task>-<index> (e.g. hooks-pre-0),
// which GenerateHookTasks emits in lockstep with this loop.
type HooksStep struct {
	Exec       *ExecMise
	Commands   []profile.HookCommand
	ConfigPath string
	Task       string // mise task-name prefix, e.g. "hooks-pre"; per-command tasks are <Task>-<i>
	StepName   string // pipeline step name, e.g. "hooks-pre"
	// Hook tasks are interactive everywhere — the generated tasks always
	// carry mise's `interactive = true` (0088) and every task runs through
	// the handover seam (0104), never through the piped runner: dotdrift
	// itself must not strip the terminal the key promises. Without a
	// terminal on the consumer's stdio mise degenerates the task to plain
	// execution (verified 2026.9.10), so terminal-less callers are
	// unchanged apart from streaming.
	// Handover runs one child command on the consumer's terminal. Injected
	// by the apply session; nil fails loud (contract 13).
	Handover apply.HandoverFunc

	obs apply.Observer // injected by the pipeline; nil = no observation
}

var (
	_ apply.Step         = (*HooksStep)(nil)
	_ apply.HandoverStep = (*HooksStep)(nil)
)

func (s *HooksStep) Name() string { return s.StepName }

// RequiresTTY classifies the step up front (0064-D4): interactive hook
// tasks run on the consumer's terminal — always (0104).
func (s *HooksStep) RequiresTTY() string {
	if len(s.Commands) > 0 {
		return "interactive hook commands run on your terminal"
	}
	return ""
}

// SetHandover injects the consumer's handover callback (apply.HandoverStep).
func (s *HooksStep) SetHandover(h apply.HandoverFunc) { s.Handover = h }

// SetObserver receives the pipeline observer (apply.observerSetter) so the
// step can announce per-command hook boundaries (issue 0071).
func (s *HooksStep) SetObserver(o apply.Observer) { s.obs = o }

func (s *HooksStep) Run(ctx context.Context) error {
	if len(s.Commands) == 0 {
		return nil
	}
	if s.Exec == nil {
		return fmt.Errorf("no mise exec configured")
	}
	// Interactive tasks with no handover fail loud (contract 13): the step
	// just classified NeedsTTY — piping an interactive task would lie.
	if s.Handover == nil {
		return fmt.Errorf("interactive hook tasks require a handover callback")
	}
	for i, c := range s.Commands {
		task := fmt.Sprintf("%s-%d", s.Task, i)
		sub := apply.SubStep{Index: i, Total: len(s.Commands), Command: c.Command}
		if s.obs != nil {
			s.obs.HookStarted(s.StepName, sub)
		}
		var err error
		var cmd *exec.Cmd
		cmd, err = s.Exec.RunTaskCmd(ctx, s.ConfigPath, task)
		if err == nil {
			err = s.Handover(cmd)
		}
		if err != nil {
			if s.obs != nil {
				s.obs.HookFailed(s.StepName, sub, err)
			}
			if c.Optional {
				log.Warn().Err(err).Str("command", c.Command).Msg("optional hook failed; continuing")
				continue
			}
			return fmt.Errorf("hook %q: %w", c.Command, err)
		}
	}
	return nil
}

func writeConfig(path, content string) error {
	if path == "" {
		return fmt.Errorf("config path is empty")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

// OverwriteTargets implements apply.OverwriteStep (M15): the copy-mode
// destinations that exist on disk — the destructive-apply confirm's
// list, in their declared (tilde) form. Symlink replacements and
// marker-scoped edits are not content overwrites; absent targets are
// first applies. Pure stat reads, matching RequiresTTY's contract.
func (s *DotfilesStep) OverwriteTargets() []string {
	if s.Plan == nil {
		return nil
	}
	var out []string
	for _, e := range s.Plan.Dotfiles.Entries {
		if e.Mode != "copy" || e.IsEdit() {
			continue
		}
		p := e.Target
		if strings.HasPrefix(p, "~/") {
			if home, err := os.UserHomeDir(); err == nil {
				p = filepath.Join(home, p[2:])
			}
		}
		if _, err := os.Lstat(p); err == nil {
			out = append(out, e.Target)
		}
	}
	return out
}
