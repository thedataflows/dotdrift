package drift_test

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
	"github.com/thedataflows/dotdrift/internal/drift"
	"github.com/thedataflows/dotdrift/internal/resolve"
)

// Unmanaged conf.d files (issue 0139): since apply never deletes in
// ~/.config/mise/conf.d (0138), status lists what the plan does not
// manage there — user files and stale dotdrift snippets — with the
// Unmanaged status, for information only.

const testMarker = "# Generated by dotdrift — do not edit.\n"

func confdPlan() *resolve.Plan {
	return &resolve.Plan{Tools: resolve.ToolsStep{
		Versions:    map[string]string{"node": "22"},
		ModuleTools: map[string]map[string]string{"shell": {"node": "22"}},
	}}
}

func TestCheckConfD_listsUnmanagedFiles(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"shell.toml": testMarker + "[tools]\nnode = \"22\"\n", // managed: in the plan
		"stale.toml": testMarker + "[tools]\ngo = \"1.25\"\n", // dotdrift's, module not in the plan
		"mine.toml":  "[tools]\npython = \"3.12\"\n",          // user file
		"notes.txt":  "hello\n",                              // user file, not mise config
	}
	for name, content := range files {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "subdir"), 0o755))

	fs := drift.CheckConfD(confdPlan(), dir)

	require.Len(t, fs, 3, "the managed snippet and the subdirectory are not listed")
	for _, f := range fs {
		require.Equal(t, "tools", f.Section)
		require.Equal(t, drift.Unmanaged, f.Status)
	}
	// ReadDir order is by file name: mine.toml, notes.txt, stale.toml.
	require.Equal(t, "conf.d/mine.toml", fs[0].Item)
	require.Contains(t, fs[0].Detail, "not written by dotdrift")
	require.Equal(t, "conf.d/notes.txt", fs[1].Item)
	require.Equal(t, "conf.d/stale.toml", fs[2].Item)
	require.Equal(t, "stale", fs[2].Module, "a stale snippet is attributed to its module name")
	require.Contains(t, fs[2].Detail, "delete")
}

func TestCheckConfD_missingDirAndNilPlan(t *testing.T) {
	require.Nil(t, drift.CheckConfD(confdPlan(), filepath.Join(t.TempDir(), "nope")))
	require.Nil(t, drift.CheckConfD(nil, t.TempDir()))
}

func TestRender_unmanagedFindingsAreNotDrift(t *testing.T) {
	var buf bytes.Buffer
	drift.Render(&buf, []drift.Finding{
		{Section: "tools", Item: "node", Status: drift.OK, Module: "shell"},
		{Section: "tools", Item: "conf.d/mine.toml", Status: drift.Unmanaged, Detail: "not written by dotdrift"},
	})
	out := buf.String()
	require.Contains(t, out, "tools:")
	require.Contains(t, out, "ok: all 1 checks passed", "unmanaged lines are not checks")
	require.Contains(t, out, "conf.d/mine.toml - not written by dotdrift (unmanaged)")
	require.Contains(t, out, "no drift", "unmanaged findings never count as drift")
}
