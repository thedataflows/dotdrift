// The tools step activates each module's tools globally with one snippet
// per module (issue 0137, replacing 0037's single fragment): mise loads
// ~/.config/mise/conf.d/*.toml as global config, so a module's installed
// tools resolve on PATH — without touching config.toml, which a profile
// may manage as a dotfile.

func TestToolsStep_writesPerModuleSnippets(t *testing.T) {
	fr := &mise.FakeRunner{}
	plan := &resolve.Plan{Tools: resolve.ToolsStep{
		Versions: map[string]string{"node": "20", "go": "1.25"},
		ModuleTools: map[string]map[string]string{
			"shell": {"node": "20"},
			"dev":   {"go": "1.25"},
		},
	}}
	dir := filepath.Join(t.TempDir(), "conf.d")
	step := &mise.ToolsStep{
		Runner: fr, Plan: plan,
		ConfigPath:  filepath.Join(t.TempDir(), "mise.toml"),
		FragmentDir: dir,
	}

	require.NoError(t, step.Run(context.Background()))

	require.True(t, fr.InstallCalled)
	shell, err := os.ReadFile(filepath.Join(dir, "shell.toml"))
	require.NoError(t, err, "each module with tools gets its own snippet")
	require.Contains(t, string(shell), "[tools]")
	require.Contains(t, string(shell), `node = "20"`)
	require.NotContains(t, string(shell), "go", "a snippet holds only its own module's tools")
	require.Contains(t, string(shell), "dotdrift", "the snippet is marked as generated")

	dev, err := os.ReadFile(filepath.Join(dir, "dev.toml"))
	require.NoError(t, err)
	require.Contains(t, string(dev), `go = "1.25"`)
}

func TestToolsStep_removesStaleSnippetsAndLegacyFragment(t *testing.T) {
	dir := t.TempDir()
	marked := "# Generated by dotdrift — do not edit.\n[tools]\nnode = \"20\"\n"
	for _, name := range []string{"gone.toml", "dotdrift.toml", "user.toml"} {
		content := marked
		if name == "user.toml" {
			content = "[tools]\nnode = \"20\"\n" // foreign: no marker
		}
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}
	fr := &mise.FakeRunner{}
	plan := &resolve.Plan{Tools: resolve.ToolsStep{
		Versions:    map[string]string{"node": "22"},
		ModuleTools: map[string]map[string]string{"shell": {"node": "22"}},
	}}
	step := &mise.ToolsStep{
		Runner: fr, Plan: plan,
		ConfigPath:  filepath.Join(t.TempDir(), "mise.toml"),
		FragmentDir: dir,
	}

	require.NoError(t, step.Run(context.Background()))

	_, err := os.Stat(filepath.Join(dir, "gone.toml"))
	require.ErrorIs(t, err, os.ErrNotExist, "a stale marked snippet keeps removed tools active")
	_, err = os.Stat(filepath.Join(dir, "dotdrift.toml"))
	require.ErrorIs(t, err, os.ErrNotExist, "the legacy combined fragment (0037) is removed")
	_, err = os.Stat(filepath.Join(dir, "user.toml"))
	require.NoError(t, err, "foreign conf.d files are never touched")
	_, err = os.Stat(filepath.Join(dir, "shell.toml"))
	require.NoError(t, err, "the current module's snippet is written")
}

func TestToolsStep_emptyPlanRemovesAllMarkedSnippets(t *testing.T) {
	dir := t.TempDir()
	marked := "# Generated by dotdrift — do not edit.\n[tools]\nnode = \"20\"\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "shell.toml"), []byte(marked), 0o644))
	fr := &mise.FakeRunner{}
	step := &mise.ToolsStep{Runner: fr, Plan: &resolve.Plan{}, FragmentDir: dir}

	require.NoError(t, step.Run(context.Background()))

	_, err := os.Stat(filepath.Join(dir, "shell.toml"))
	require.ErrorIs(t, err, os.ErrNotExist,
		"a stale snippet keeps removed tools active — it must be removed")
	require.False(t, fr.InstallCalled, "nothing to install")
}

func TestToolsStep_noFragmentDirSkipsWrite(t *testing.T) {
	fr := &mise.FakeRunner{}
	plan := &resolve.Plan{Tools: resolve.ToolsStep{Versions: map[string]string{"node": "20"}}}
	step := &mise.ToolsStep{Runner: fr, Plan: plan, ConfigPath: filepath.Join(t.TempDir(), "mise.toml")}

	require.NoError(t, step.Run(context.Background()))
	require.True(t, fr.InstallCalled)
}

func TestToolsFragmentDir_honorsXDG(t *testing.T) {
	t.Setenv("XDG_CONFIG_HOME", "/xdg")
	require.Equal(t, "/xdg/mise/conf.d", mise.ToolsFragmentDir())

	t.Setenv("XDG_CONFIG_HOME", "")
	home, err := os.UserHomeDir()
	require.NoError(t, err)
	require.Equal(t, filepath.Join(home, ".config", "mise", "conf.d"), mise.ToolsFragmentDir())
}
